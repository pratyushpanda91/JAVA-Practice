public class Solution {
    public void pattern16(int n) {
        char q='A';
        for(int i = 1;i<=n;i++){
            
            for(int j = 1;j<=i;j++){
                System.out.print(q);
            }
            q++;
            
        System.out.println();
        
        }
    }
} {
  
}
